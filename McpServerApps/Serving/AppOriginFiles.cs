using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Domain.Apps;
using Domain.DTOs.WebChat;

namespace McpServerApps.Serving;

// What the apps server adds to every built app's origin, under /_app/, whatever the agent wrote: the
// web manifest and icon that make the origin installable as an app of its own, the service worker that
// keeps its files for offline, the client library, and the three tags that bring them into each page.
// Files, never inline script: the policy (AppContentPolicy) runs none.
public static partial class AppOriginFiles
{
    public const string Prefix = "/_app/";
    public const string ManifestPath = Prefix + "manifest.webmanifest";
    public const string IconPath = Prefix + "icon.svg";
    public const string WorkerPath = Prefix + "sw.js";
    public const string RegisterPath = Prefix + "register.js";
    public const string LibraryPath = Prefix + "apps.js";
    public const string ModulePath = Prefix + "apps.mjs";

    // Every file the server serves under Prefix on an app's origin (the sign-in's callback is no file).
    public static readonly IReadOnlySet<string> Paths =
        new HashSet<string>([ManifestPath, IconPath, WorkerPath, RegisterPath, LibraryPath, ModulePath], StringComparer.Ordinal);

    // The manifest is fetched with the page's cookie (use-credentials), since the origin opens to its
    // app session alone; the library runs before the app's own scripts, the registration after parsing.
    public const string Tags =
        $"<link rel=\"manifest\" href=\"{ManifestPath}\" crossorigin=\"use-credentials\">"
        + $"<script src=\"{LibraryPath}\"></script>"
        + $"<script src=\"{RegisterPath}\" defer></script>";

    // The response header naming the version a published origin served an answer at (Version).
    public const string VersionHeader = "X-App-Version";

    // What a published origin's worker keeps its files under: its served commit, its policy (so an owner
    // narrowing an approval replaces the shell kept for offline, which carries the policy it was served
    // with) and this server's own generated files (so a new client library replaces the kept one). Any of
    // them changing changes the worker's bytes, which the browser's update check installs.
    public static string Version(string commit, string policy) =>
        Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes($"{commit}\n{policy}\n{_filesStamp}")))[..16];

    // The worker. A published origin's (a version) keeps the app's own files cache first under that
    // version, so the shell opens without waiting on them, and a publish is a new version: its worker drops
    // the old cache. A navigation still reaches the server first, so a sign-in, a closed app, a removed page
    // or a new version is never hidden behind a kept page; the kept page is the answer only when the
    // network is gone, and a client route falls back to the kept root. A page served at another version than
    // the worker's (a publish since the worker installed) loads its files from the network until the new
    // worker takes over. The preview (no version) is the author's working tree, changing with every write:
    // network first, the cache only offline. The household's data (/_vfs/), error reports (/_errors) and
    // the sign-in are never touched, never kept: a kept read would show one viewer's data to whoever opens
    // the phone next.
    public static string Worker(string? version) =>
        $$"""
          // Generated by the apps server for this built app's origin.
          const VERSION = {{JsonSerializer.Serialize(version)}};
          const PREFIX = 'app-files';
          const CACHE = `${PREFIX}-${VERSION ?? 'preview'}`;
          const PASSED_BY = ['/_vfs/', '{{AppErrors.OriginPath}}', '{{AppSignIn.CallbackPath}}', '{{WorkerPath}}'];
          const ROOT = '/';
          // The version each page was served at, by the window it opened in.
          const served = new Map();

          self.addEventListener('install', () => self.skipWaiting());
          self.addEventListener('activate', event => event.waitUntil((async () => {
            const names = await caches.keys();
            await Promise.all(names.filter(name => name.startsWith(PREFIX) && name !== CACHE).map(name => caches.delete(name)));
            await self.clients.claim();
          })()));

          const keep = (event, request, response) => {
            if (response.ok && response.type === 'basic') {
              const kept = response.clone();
              event.waitUntil(caches.open(CACHE).then(cache => cache.put(request, kept)));
            }
          };

          const kept = async request => {
            const cache = await caches.open(CACHE);
            return await cache.match(request) || (request.mode === 'navigate' ? await cache.match(ROOT) : undefined) || Response.error();
          };

          const networkFirst = async event => {
            try {
              const response = await fetch(event.request);
              keep(event, event.request, response);
              return response;
            } catch {
              return kept(event.request);
            }
          };

          const navigate = async event => {
            let response;
            try {
              response = await fetch(event.request);
            } catch {
              return kept(event.request);
            }
            const version = response.headers.get('{{VersionHeader}}');
            if (event.resultingClientId) {
              served.set(event.resultingClientId, version);
            }
            if (version === VERSION) {
              keep(event, event.request, response);
            }
            return response;
          };

          const file = async event => {
            if ((served.get(event.clientId) ?? VERSION) !== VERSION) {
              return fetch(event.request);
            }
            const cache = await caches.open(CACHE);
            const hit = await cache.match(event.request);
            if (hit) {
              return hit;
            }
            const response = await fetch(event.request);
            keep(event, event.request, response);
            return response;
          };

          self.addEventListener('fetch', event => {
            const request = event.request;
            const url = new URL(request.url);
            if (request.method !== 'GET' || url.origin !== self.location.origin
                || PASSED_BY.some(path => url.pathname.startsWith(path))) {
              return;
            }
            event.respondWith(VERSION === null ? networkFirst(event) : request.mode === 'navigate' ? navigate(event) : file(event));
          });
          """;

    // What a removed app's origin answers its worker's update check with: a worker that takes over,
    // forgets everything the old one kept, unregisters, and reopens each open window, which then
    // reaches the server and its removed page.
    public const string RemovedWorker =
        """
        // Generated by the apps server: this built app was removed.
        self.addEventListener('install', () => self.skipWaiting());
        self.addEventListener('activate', event => event.waitUntil((async () => {
          await Promise.all((await caches.keys()).map(name => caches.delete(name)));
          await self.registration.unregister();
          const windows = await self.clients.matchAll({ type: 'window' });
          windows.forEach(client => client.navigate(client.url));
        })()));
        """;

    // Plain and self-contained: the closed policy loads nothing, styles included.
    public const string RemovedPage =
        """
        <!doctype html>
        <html lang="en">
        <meta charset="utf-8">
        <meta name="viewport" content="width=device-width, initial-scale=1">
        <title>App removed</title>
        <h1>This app was removed</h1>
        <p>Whoever built it deleted it. Ask your assistant for a new one if you still need it.</p>
        </html>
        """;

    public const string Register =
        """
        // Generated by the apps server: the origin's service worker, scoped at its root.
        if ('serviceWorker' in navigator) {
          navigator.serviceWorker.register('/_app/sw.js', { scope: '/' });
        }
        """;

    // How a built app reads the household: each of the file tools' reads, by the tool's own arguments,
    // answered with the tool's own result — and a refusal thrown as a ReadError carrying the tools'
    // envelope (errorCode, message, retryable, hint), with the path it was about. Small and dependent on
    // nothing; one expression, so the classic script and the module are the same object, and the error
    // listeners below are installed once whichever loads first.
    //
    // It also tells the server what went wrong (POST /_errors, AppErrors): every uncaught error, unhandled
    // rejection and failed or refused read, so the agent can see why an app broke on somebody's phone.
    // - What went wrong, never what was read: a read's operation, path and envelope; an Error's name,
    //   message and stack; a thrown or rejected value that is no Error by its type alone.
    // - A failed read is reported as the read, once: its ReadError is never reported again as the rejection
    //   or uncaught error it becomes when the app does not catch it.
    // - One broken loop is one report: the same error is sent once a page, and at most ten a minute, well
    //   under the server's own limit a session (Errors:PerSessionPerMinute).
    // - Reporting never throws into the app, and a report that fails is dropped, never reported itself.
    private static readonly string Reader =
        $$"""
        (() => {
          'use strict';
          class ReadError extends Error {
            constructor(operation, path, envelope) {
              super(envelope.message);
              this.name = 'ReadError';
              this.operation = operation;
              this.path = path;
              this.errorCode = envelope.errorCode;
              this.retryable = envelope.retryable === true;
              this.hint = envelope.hint;
              this.envelope = envelope;
            }
          }

          const clip = (text, length) => typeof text === 'string' && text.length > 0 ? text.slice(0, length) : undefined;
          const reported = new WeakSet();
          const seen = new Set();
          let minute = 0;
          let sent = 0;
          const report = body => {
            try {
              const key = JSON.stringify([body.kind, body.message, body.read?.operation, body.read?.path]);
              const now = Date.now();
              if (now - minute >= 60000) {
                minute = now;
                sent = 0;
              }
              if (seen.has(key) || sent >= 10) {
                return;
              }
              seen.add(key);
              sent++;
              fetch('{{AppErrors.OriginPath}}', {
                method: 'POST', credentials: 'same-origin', cache: 'no-store', keepalive: true,
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ ...body, route: location.pathname.slice(0, {{AppErrorReport.MaxRoute}}) })
              }).catch(() => {});
            } catch {
              // Nothing about reporting reaches the app.
            }
          };
          const described = (value, otherwise) => value instanceof Error
            ? { message: clip(`${value.name}: ${value.message}`, {{AppErrorReport.MaxMessage}}), stack: clip(value.stack, {{AppErrorReport.MaxStack}}) }
            : { message: otherwise };
          const typeOf = value => value === null ? 'null' : typeof value;

          // A resource that failed to load is an event of the element's, not the window's ErrorEvent.
          addEventListener('error', event => {
            if (!(event instanceof ErrorEvent) || reported.has(event.error)) {
              return;
            }
            report({ kind: '{{AppErrors.Kinds.Error}}', ...described(event.error, event.error == null
              ? clip(event.message, {{AppErrorReport.MaxMessage}}) ?? 'Script error.'
              : `Uncaught ${typeOf(event.error)}, not an Error`) });
          });
          addEventListener('unhandledrejection', event => {
            if (reported.has(event.reason)) {
              return;
            }
            report({ kind: '{{AppErrors.Kinds.Rejection}}',
              ...described(event.reason, `A promise was rejected with ${typeOf(event.reason)}, not an Error`) });
          });

          const refused = (operation, path, envelope) => {
            const error = new ReadError(operation, path, envelope);
            reported.add(error);
            const message = clip(envelope.message, {{AppErrorReport.MaxMessage}});
            report({
              kind: '{{AppErrors.Kinds.Read}}', message: message ?? 'The read failed.',
              read: {
                operation,
                path: typeof path === 'string' && path.startsWith('/') ? clip(path, {{AppErrorReport.MaxRoute}}) : undefined,
                envelope: { errorCode: envelope.errorCode, message: message ?? '', hint: clip(envelope.hint, {{AppErrorReport.MaxMessage}}) }
              }
            });
            return error;
          };

          // Not the tools' envelope: no app session (the origin's one 404), or nobody answered.
          const unanswered = status => status === 404 || status === 401
            ? { ok: false, errorCode: 'authentication', retryable: false,
                message: 'This app is not signed in, so nothing was read.', hint: 'Reload the page to sign in again.' }
            : { ok: false, errorCode: 'transient_dependency', retryable: true,
                message: `The read was not answered (HTTP ${status}).`, hint: 'Read again in a moment.' };

          const send = async (operation, path, args) => {
            const response = await fetch(`/_vfs/${operation}`, {
              method: 'POST', credentials: 'same-origin', cache: 'no-store',
              headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(args)
            });
            if (response.ok) {
              return response;
            }
            const envelope = await response.json().catch(() => null);
            throw refused(operation, path, envelope?.ok === false ? envelope : unanswered(response.status));
          };
          const json = async (operation, path, args) => (await send(operation, path, args)).json();

          return Object.freeze({
            read: (filePath, options = {}) => json('read', filePath, { ...options, filePath }),
            glob: (basePath, pattern) => json('glob', basePath, { basePath, pattern }),
            info: path => json('info', path, { path }),
            search: (query, options = {}) =>
              json('search', options.filePath ?? options.directoryPath, { ...options, query }),
            query: (path, sql, options = {}) => json('query', path, { ...options, path, sql }),
            blob: async path => (await send('blob', path, { path })).blob(),
            ReadError
          });
        })()
        """;

    // A classic script, run before the app's own scripts, so `apps` is there for every one of them.
    public static readonly string Library =
        "// Generated by the apps server: the client library a built app reads the household through.\n"
        + "globalThis.apps ??= " + Reader + ";\n";

    // The same library as an ES module, for an app that imports it.
    public static readonly string Module =
        "// Generated by the apps server: the client library a built app reads the household through.\n"
        + "const apps = (globalThis.apps ??= " + Reader + ");\n"
        + "export default apps;\n"
        + "export const { read, glob, info, search, query, blob, ReadError } = apps;\n";

    // What this server's generated files are, so a new build's library or worker is a new version.
    private static readonly string _filesStamp = Convert.ToHexStringLower(SHA256.HashData(
        Encoding.UTF8.GetBytes(string.Join("\n", Library, Module, Register, Worker("stamp")))));

    public static string Manifest(AppManifest manifest) => JsonSerializer.Serialize(new
    {
        name = manifest.Name,
        short_name = manifest.ShortName ?? manifest.Name,
        description = manifest.Description,
        id = "/",
        start_url = "/",
        scope = "/",
        display = "standalone",
        background_color = manifest.AccentColor,
        theme_color = manifest.AccentColor,
        icons = new[] { new { src = IconPath, sizes = "any", type = "image/svg+xml", purpose = "any" } }
    });

    public static string Icon(AppManifest manifest) => SpaceIcon.Svg(manifest.AccentColor);

    // The tags go first inside <head>, else right after <html>, else after the doctype, else first:
    // early enough that the library exists before any of the app's scripts runs.
    public static string Inject(string html)
    {
        var anchor = new[] { Head(), Html(), Doctype() }.Select(r => r.Match(html)).FirstOrDefault(m => m.Success);
        var at = anchor is null ? 0 : anchor.Index + anchor.Length;
        return html.Insert(at, Tags);
    }

    [GeneratedRegex(@"<head\b[^>]*>", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant)]
    private static partial Regex Head();

    [GeneratedRegex(@"<html\b[^>]*>", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant)]
    private static partial Regex Html();

    [GeneratedRegex(@"<!doctype\b[^>]*>", RegexOptions.IgnoreCase | RegexOptions.CultureInvariant)]
    private static partial Regex Doctype();
}